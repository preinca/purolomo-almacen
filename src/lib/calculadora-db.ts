const AHORA = `to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`;

export async function asegurarCalculadora(db: Db) {
  await db.exec(`
CREATE TABLE IF NOT EXISTS calc_recetas (
  id TEXT PRIMARY KEY,
  nombre TEXT NOT NULL,
  planta TEXT NOT NULL,
  kg_batch DOUBLE PRECISION,
  fecha_formula TEXT NOT NULL DEFAULT '',
  nota_empaque TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS calc_receta_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receta_id TEXT NOT NULL,
  codigo TEXT NOT NULL,
  nombre TEXT NOT NULL,
  tipo TEXT NOT NULL CHECK (tipo IN ('mpnc', 'empaque')),
  kg_por_batch DOUBLE PRECISION,
  unidad TEXT NOT NULL DEFAULT 'kg',
  cantidad_observada DOUBLE PRECISION,
  nota TEXT NOT NULL DEFAULT '',
  orden INTEGER NOT NULL DEFAULT 0,
  UNIQUE (receta_id, codigo, tipo)
);
CREATE TABLE IF NOT EXISTS calc_plan_filas (
  orden INTEGER PRIMARY KEY,
  planta TEXT NOT NULL,
  nombre TEXT NOT NULL,
  receta_id TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS calc_catalogo (
  codigo TEXT NOT NULL,
  tipo TEXT NOT NULL CHECK (tipo IN ('mpnc', 'empaque')),
  nombre TEXT NOT NULL,
  unidad TEXT NOT NULL,
  nota TEXT NOT NULL DEFAULT '',
  orden INTEGER NOT NULL,
  PRIMARY KEY (codigo, tipo)
);
CREATE TABLE IF NOT EXISTS calc_planes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anio INTEGER NOT NULL,
  semana INTEGER NOT NULL CHECK (semana BETWEEN 1 AND 53),
  creado_en TEXT NOT NULL DEFAULT ${AHORA},
  actualizado_en TEXT NOT NULL DEFAULT ${AHORA},
  usuario TEXT NOT NULL DEFAULT '',
  cerrado INTEGER NOT NULL DEFAULT 0,
  UNIQUE (anio, semana)
);
ALTER TABLE calc_planes ADD COLUMN IF NOT EXISTS cerrado INTEGER NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS calc_plan_batches (
  plan_id INTEGER NOT NULL,
  fila_orden INTEGER NOT NULL,
  lunes DOUBLE PRECISION NOT NULL DEFAULT 0,
  martes DOUBLE PRECISION NOT NULL DEFAULT 0,
  miercoles DOUBLE PRECISION NOT NULL DEFAULT 0,
  jueves DOUBLE PRECISION NOT NULL DEFAULT 0,
  viernes DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY (plan_id, fila_orden)
);
CREATE TABLE IF NOT EXISTS calc_plan_solicitado (
  plan_id INTEGER NOT NULL,
  codigo TEXT NOT NULL,
  tipo TEXT NOT NULL CHECK (tipo IN ('mpnc', 'empaque')),
  cantidad DOUBLE PRECISION,
  PRIMARY KEY (plan_id, codigo, tipo)
);
`);
}

type Semilla = {
  plantas: string[];
  productos_plan: { planta: string; nombre: string; receta_id: string; order: number }[];
  recetas: {
    id: string;
    nombre: string;
    planta: string;
    kg_batch: number | null;
    fecha_formula?: string;
    nota_empaque?: string;
    items: { codigo: string; nombre: string; kg_por_batch: number; tipo: string; nota?: string }[];
    empaque: {
      codigo: string;
      nombre: string;
      cantidad_por_batch: number | null;
      unidad: string;
      tipo: string;
      cantidad_observada?: number;
      nota?: string;
    }[];
  }[];
  catalogo_mp: { codigo: string; nombre: string; unidad: string; tipo: string; nota?: string }[];
};

function leerSemilla(): Semilla {
  const archivo = path.join(process.cwd(), "data", "seed-calculadora.json");
  return JSON.parse(fs.readFileSync(archivo, "utf8")) as Semilla;
}

export async function prepararCalculadora(db: Db) {
  await asegurarCalculadora(db);
  const fila = await db.get<{ n: number }>("SELECT COUNT(*)::int AS n FROM calc_plan_filas");
  if (Number(fila?.n ?? 0) > 0) return;
  await sembrar(db, leerSemilla());
}

async function sembrar(db: Db, semilla: Semilla) {
  for (const receta of semilla.recetas) {
    await db.run(
      `INSERT INTO calc_recetas (id, nombre, planta, kg_batch, fecha_formula, nota_empaque)
       VALUES (?, ?, ?, ?, ?, ?)
       ON CONFLICT (id) DO NOTHING`,
      receta.id,
      receta.nombre,
      receta.planta,
      receta.kg_batch,
      receta.fecha_formula ?? "",
      receta.nota_empaque ?? "",
    );
    let orden = 0;
    for (const item of receta.items) {
      orden += 1;
      await db.run(
        `INSERT INTO calc_receta_items (receta_id, codigo, nombre, tipo, kg_por_batch, unidad, nota, orden)
         VALUES (?, ?, ?, 'mpnc', ?, 'kg', ?, ?)
         ON CONFLICT (receta_id, codigo, tipo) DO NOTHING`,
        receta.id,
        item.codigo,
        item.nombre,
        item.kg_por_batch,
        item.nota ?? "",
        orden,
      );
    }
    for (const item of receta.empaque) {
      orden += 1;
      await db.run(
        `INSERT INTO calc_receta_items
           (receta_id, codigo, nombre, tipo, kg_por_batch, unidad, cantidad_observada, nota, orden)
         VALUES (?, ?, ?, 'empaque', ?, ?, ?, ?, ?)
         ON CONFLICT (receta_id, codigo, tipo) DO NOTHING`,
        receta.id,
        item.codigo,
        item.nombre,
        item.cantidad_por_batch,
        item.unidad,
        item.cantidad_observada ?? null,
        item.nota ?? "",
        orden,
      );
    }
  }
  for (const fila of semilla.productos_plan) {
    await db.run(
      `INSERT INTO calc_plan_filas (orden, planta, nombre, receta_id) VALUES (?, ?, ?, ?)
       ON CONFLICT (orden) DO NOTHING`,
      fila.order,
      fila.planta,
      fila.nombre,
      fila.receta_id,
    );
  }
  for (let i = 0; i < semilla.catalogo_mp.length; i += 1) {
    const item = semilla.catalogo_mp[i];
    if (!item) continue;
    await db.run(
      `INSERT INTO calc_catalogo (codigo, tipo, nombre, unidad, nota, orden) VALUES (?, ?, ?, ?, ?, ?)
       ON CONFLICT (codigo, tipo) DO NOTHING`,
      item.codigo,
      item.tipo,
      item.nombre,
      item.unidad,
      item.nota ?? "",
      i + 1,
    );
  }
}

