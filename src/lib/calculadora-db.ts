export async function agregarItemReceta(
  db: Db,
  recetaId: string,
  tipo: "mpnc" | "empaque",
  codigo: string,
  nombre: string,
  kg: number | null,
  unidad: string,
) {
  await prepararCalculadora(db);
  const limpio = codigo.trim().toUpperCase();
  const titulo = nombre.trim();
  if (!/^[A-Z0-9]{4,20}$/.test(limpio)) return { ok: false as const, error: "El código no es válido." };
  if (titulo.length < 2) return { ok: false as const, error: "Escribe el nombre." };
  if (tipo === "mpnc" && (kg === null || !(kg >= 0))) return { ok: false as const, error: "Escribe los kilos por batch." };
  const existe = await db.get("SELECT id FROM calc_recetas WHERE id = ?", recetaId);
  if (!existe) return { ok: false as const, error: "No existe esa receta." };
  const orden = await db.get<{ n: number }>("SELECT COALESCE(MAX(orden), 0) + 1 AS n FROM calc_receta_items WHERE receta_id = ?", recetaId);
  const cambios = await db.run(
    `INSERT INTO calc_receta_items (receta_id, codigo, nombre, tipo, kg_por_batch, unidad, orden)
     VALUES (?, ?, ?, ?, ?, ?, ?)
     ON CONFLICT (receta_id, codigo, tipo) DO NOTHING`,
    recetaId,
    limpio,
    titulo,
    tipo,
    kg,
    unidad.trim() || (tipo === "mpnc" ? "kg" : "unds"),
    Number(orden?.n ?? 1),
  );
  if (cambios === 0) return { ok: false as const, error: "Ese código ya está en la receta." };
  await db.run(
    `INSERT INTO calc_catalogo (codigo, tipo, nombre, unidad, orden)
     VALUES (?, ?, ?, ?, (SELECT COALESCE(MAX(orden), 0) + 1 FROM calc_catalogo))
     ON CONFLICT (codigo, tipo) DO NOTHING`,
    limpio,
    tipo,
    titulo,
    unidad.trim() || (tipo === "mpnc" ? "kg" : "unds"),
  );
  return { ok: true as const };
}

export async function importarCsvReceta(db: Db, filas: { receta: string; codigo: string; ingrediente: string; kgPorBatch: number }[]) {
  await prepararCalculadora(db);
  let n = 0;
  for (const fila of filas) {
    const receta = await db.get("SELECT id FROM calc_recetas WHERE id = ?", fila.receta);
    if (!receta) return { ok: false as const, error: `No existe la receta ${fila.receta}.` };
    const cambios = await db.run(
      "UPDATE calc_receta_items SET kg_por_batch = ?, nombre = ? WHERE receta_id = ? AND codigo = ? AND tipo = 'mpnc'",
      fila.kgPorBatch,
      fila.ingrediente,
      fila.receta,
      fila.codigo,
    );
    if (cambios === 0) {
      const agregado = await agregarItemReceta(db, fila.receta, "mpnc", fila.codigo, fila.ingrediente, fila.kgPorBatch, "kg");
      if (!agregado.ok) return agregado;
    }
    n += 1;
  }
  return { ok: true as const, n };
}

