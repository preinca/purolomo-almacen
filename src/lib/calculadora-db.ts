async function planAbierto(db: Db, id: number) {
  const plan = await db.get<Record<string, unknown>>("SELECT id, COALESCE(cerrado, 0) AS cerrado FROM calc_planes WHERE id = ?", id);
  if (!plan) return { ok: false as const, error: "No existe esa solicitud." };
  if (Number(plan.cerrado) === 1) return { ok: false as const, error: "Esta solicitud ya está guardada y no se puede modificar." };
  return { ok: true as const };
}

export async function guardarBatches(db: Db, id: number, filas: { orden: number; batches: BatchesDia }[], usuario: string) {
  await prepararCalculadora(db);
  const abierto = await planAbierto(db, id);
  if (!abierto.ok) return abierto;
  for (const fila of filas) {
    const b = fila.batches;
    if (DIAS.some((dia) => !Number.isFinite(b[dia]) || b[dia] < 0)) {
      return { ok: false as const, error: "Los batches tienen que ser cero o más." };
    }
    await db.run(
      `INSERT INTO calc_plan_batches (plan_id, fila_orden, lunes, martes, miercoles, jueves, viernes)
       VALUES (?, ?, ?, ?, ?, ?, ?)
       ON CONFLICT (plan_id, fila_orden) DO UPDATE SET
         lunes = excluded.lunes, martes = excluded.martes, miercoles = excluded.miercoles,
         jueves = excluded.jueves, viernes = excluded.viernes`,
      id,
      fila.orden,
      b.lunes,
      b.martes,
      b.miercoles,
      b.jueves,
      b.viernes,
    );
  }
  await db.run(`UPDATE calc_planes SET usuario = ?, actualizado_en = ${AHORA} WHERE id = ?`, usuario, id);
  return { ok: true as const };
}

export async function guardarSolicitado(
  db: Db,
  id: number,
  codigo: string,
  tipo: "mpnc" | "empaque",
  cantidad: number | null,
) {
  await prepararCalculadora(db);
  const abierto = await planAbierto(db, id);
  if (!abierto.ok) return abierto;
  if (cantidad !== null && (!Number.isFinite(cantidad) || cantidad < 0)) {
    return { ok: false as const, error: "La cantidad solicitada tiene que ser cero o más." };
  }
  if (cantidad === null) {
    await db.run("DELETE FROM calc_plan_solicitado WHERE plan_id = ? AND codigo = ? AND tipo = ?", id, codigo, tipo);
  } else {
    await db.run(
      `INSERT INTO calc_plan_solicitado (plan_id, codigo, tipo, cantidad) VALUES (?, ?, ?, ?)
       ON CONFLICT (plan_id, codigo, tipo) DO UPDATE SET cantidad = excluded.cantidad`,
      id,
      codigo,
      tipo,
      cantidad,
    );
  }
  return { ok: true as const };
}

export async function cerrarSolicitud(
  db: Db,
  id: number,
  filas: { orden: number; batches: BatchesDia }[],
  pedidos: { codigo: string; tipo: "mpnc" | "empaque"; cantidad: number | null }[],
  usuario: string,
) {
  const guardado = await guardarBatches(db, id, filas, usuario);
  if (!guardado.ok) return guardado;
  for (const pedido of pedidos) {
    const resultado = await guardarSolicitado(db, id, pedido.codigo, pedido.tipo, pedido.cantidad);
    if (!resultado.ok) return resultado;
  }
  await db.run(`UPDATE calc_planes SET cerrado = 1, usuario = ?, actualizado_en = ${AHORA} WHERE id = ?`, usuario, id);
  return { ok: true as const };
}

export type FilaResultado = TotalCodigo & { solicitada: number | null; orden: number };

export async function resultadoPlan(db: Db, id: number) {
  const plan = await cargarPlan(db, id);
  if (!plan) return undefined;
  const porFila = new Map(plan.filas.map((fila) => [fila.orden, fila.batches]));
  const mpnc = calcularMpnc(plan.filas, plan.recetas, porFila);
  const empaque = calcularEmpaque(plan.filas, plan.recetas, porFila);
  const catalogo = await db.all<Record<string, unknown>>("SELECT codigo, tipo, nombre, unidad, orden FROM calc_catalogo ORDER BY orden");
  const ajustes = await db.all<Record<string, unknown>>(
    "SELECT codigo, tipo, cantidad FROM calc_plan_solicitado WHERE plan_id = ?",
    id,
  );
  const ajuste = new Map(ajustes.map((fila) => [`${fila.tipo}:${fila.codigo}`, fila.cantidad === null ? null : Number(fila.cantidad)]));
  const ordenCat = new Map(catalogo.map((fila) => [`${fila.tipo}:${fila.codigo}`, Number(fila.orden)]));
  const nombreCat = new Map(catalogo.map((fila) => [`${fila.tipo}:${fila.codigo}`, { nombre: String(fila.nombre), unidad: String(fila.unidad) }]));

  const presentar = (totales: TotalCodigo[]) =>
    totales
      .map((total) => {
        const clave = `${total.tipo}:${total.codigo}`;
        const cat = nombreCat.get(clave);
        return {
          ...total,
          nombre: cat?.nombre || total.nombre,
          unidad: cat?.unidad || total.unidad,
          solicitada: ajuste.has(clave) ? (ajuste.get(clave) ?? null) : null,
          orden: ordenCat.get(clave) ?? 10000,
        };
      })
      .sort((a, b) => a.orden - b.orden || a.codigo.localeCompare(b.codigo));

  return {
    plan: { id: plan.id, anio: plan.anio, semana: plan.semana },
    mpnc: presentar(mpnc).filter((fila) => (fila.cantidad ?? 0) > 0 || fila.solicitada !== null),
    empaque: presentar(empaque),
  };
}

