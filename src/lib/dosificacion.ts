import type { Db } from "./db";
import { buscarEntrada } from "./entrada-paleta";
import { buscarPaletaKardex, kardexEstaConfigurado } from "./kardex-externo";
import type { Resultado } from "./lotes";
import { partirToken } from "./token-paleta";

const TABLA = `
CREATE TABLE IF NOT EXISTS dosificaciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token TEXT NOT NULL,
  codigo TEXT NOT NULL,
  descripcion TEXT NOT NULL,
  nucleo TEXT NOT NULL,
  peso_unitario DOUBLE PRECISION NOT NULL CHECK (peso_unitario > 0),
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  peso_total DOUBLE PRECISION NOT NULL CHECK (peso_total > 0),
  usuario TEXT NOT NULL DEFAULT '',
  creado_en TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE INDEX IF NOT EXISTS idx_dosificaciones_creado ON dosificaciones (creado_en DESC, id DESC);
`;

export type ProductoDosificacion = {
  token: string;
  codigo: string;
  descripcion: string;
  origen: "entrada" | "kardex" | "manual";
};

export type Dosificacion = ProductoDosificacion & {
  id: number;
  nucleo: string;
  pesoUnitario: number;
  cantidad: number;
  pesoTotal: number;
  usuario: string;
  creadoEn: string;
};

export function pesoTotalPaleta(pesoUnitario: number, cantidad: number) {
  if (!Number.isFinite(pesoUnitario) || !Number.isFinite(cantidad)) return null;
  if (pesoUnitario <= 0 || !Number.isInteger(cantidad) || cantidad <= 0) return null;
  return Math.round(pesoUnitario * cantidad * 1000) / 1000;
}

export async function asegurarDosificaciones(db: Db) {
  await db.exec(TABLA);
}

/** El QR de la paleta es el de la entrada. Primero la copia local, después el kárdex. */
export async function consultarProductoDosificacion(db: Db, tokenTexto: string): Promise<Resultado<ProductoDosificacion>> {
  const partes = partirToken(tokenTexto);
  if (!partes.ok) return partes;

  const local = await buscarEntrada(db, partes.value.token);
  if (local) {
    return {
      ok: true,
      value: {
        token: local.token,
        codigo: local.codigo,
        descripcion: local.producto,
        origen: "entrada",
      },
    };
  }

  if (kardexEstaConfigurado()) {
    const remoto = await buscarPaletaKardex(partes.value.token, db);
    if (remoto.ok && remoto.value.descripcion) {
      return {
        ok: true,
        value: {
          token: partes.value.token,
          codigo: remoto.value.codigo || partes.value.codigo,
          descripcion: remoto.value.descripcion,
          origen: "kardex",
        },
      };
    }
    if (!remoto.ok && remoto.tipo !== "caido" && remoto.tipo !== "no_configurado") {
      return {
        ok: true,
        value: {
          token: partes.value.token,
          codigo: partes.value.codigo,
          descripcion: "",
          origen: "manual",
        },
      };
    }
  }

  return {
    ok: true,
    value: {
      token: partes.value.token,
      codigo: partes.value.codigo,
      descripcion: "",
      origen: "manual",
    },
  };
}

export async function guardarDosificacion(
  db: Db,
  input: {
    token: string;
    codigo: string;
    descripcion: string;
    nucleo: string;
    pesoUnitario: number;
    cantidad: number;
  },
  usuario: string,
): Promise<Resultado<Dosificacion>> {
  await asegurarDosificaciones(db);
  const partes = partirToken(input.token);
  if (!partes.ok) return partes;
  const codigo = input.codigo.trim().toUpperCase();
  const descripcion = input.descripcion.trim().replace(/\s+/g, " ");
  const nucleo = input.nucleo.trim();
  const pesoTotal = pesoTotalPaleta(input.pesoUnitario, input.cantidad);
  if (!/^[A-Z0-9]{4,20}$/.test(codigo)) return { ok: false, error: "El código del producto no es válido." };
  if (descripcion.length < 2) return { ok: false, error: "Escribe el nombre del producto." };
  if (nucleo.length < 1 || nucleo.length > 40) return { ok: false, error: "Escribe el número de núcleo." };
  if (pesoTotal === null) return { ok: false, error: "El peso unitario y la cantidad tienen que ser mayores que cero." };

  await db.run(
    `INSERT INTO dosificaciones (token, codigo, descripcion, nucleo, peso_unitario, cantidad, peso_total, usuario)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
    partes.value.token,
    codigo,
    descripcion,
    nucleo,
    input.pesoUnitario,
    input.cantidad,
    pesoTotal,
    usuario,
  );
  const guardada = await db.get<Record<string, unknown>>(
    "SELECT * FROM dosificaciones WHERE token = ? ORDER BY id DESC LIMIT 1",
    partes.value.token,
  );
  if (!guardada) return { ok: false, error: "No se pudo guardar la dosificación." };
  return { ok: true, value: fila(guardada) };
}

export async function listarDosificaciones(db: Db, limite = 30) {
  await asegurarDosificaciones(db);
  const filas = await db.all<Record<string, unknown>>(
    "SELECT * FROM dosificaciones ORDER BY creado_en DESC, id DESC LIMIT ?",
    limite,
  );
  return filas.map(fila);
}

function fila(row: Record<string, unknown>): Dosificacion {
  return {
    id: Number(row.id),
    token: String(row.token),
    codigo: String(row.codigo),
    descripcion: String(row.descripcion),
    origen: "manual",
    nucleo: String(row.nucleo),
    pesoUnitario: Number(row.peso_unitario),
    cantidad: Number(row.cantidad),
    pesoTotal: Number(row.peso_total),
    usuario: String(row.usuario ?? ""),
    creadoEn: String(row.creado_en),
  };
}
